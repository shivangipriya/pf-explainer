"use strict";
// Node tests for PF Rejection Explainer. Run: node pf-test.js
const fs = require("fs");
const html = fs.readFileSync(__dirname + "/index.html", "utf8");

let passed = 0, failed = 0;
function ok(cond, name) {
  if (cond) { passed++; }
  else { failed++; console.error("FAIL: " + name); }
}

// --- structural ---
ok(/<html lang="en">/.test(html), "lang attribute set");
ok(/<meta name="viewport"/.test(html), "viewport meta present");
ok(/role="tablist"/.test(html) && /role="tab"/.test(html) && /role="tabpanel"/.test(html), "tabs have ARIA roles");
ok(html.indexOf("http://") === -1 && html.indexOf("https://") === -1 || /epfindia\.gov\.in/.test(html), "no unexpected external URLs");
ok(!/src="http/.test(html) && !/<link[^>]+href="http/.test(html), "no external resources loaded (links only)");
ok(html.indexOf("Maintained by <a href=\"https://www.linkedin.com/in/shivangii-priyaa\"") > -1 && html.indexOf(">Shivangi Priya</a>.") > -1, "attribution line links to LinkedIn");
ok(!/AI assistance|built with AI|generated by/i.test(html), "no AI-attribution wording");
ok(!/Coursera|Educlaas|Roehampton/i.test(html), "no excluded institution names");

// --- explainer substance ---
ok(/rejected for many reasons/.test(html), "neutral opening framing present");
ok(!/usually a fixable paperwork problem/.test(html), "no 'usually fixable' assurance");
ok(!/Most rejections are resolved/.test(html), "no most-resolve assurance");
ok(/never a guarantee of approval/.test(html), "no-approval-guarantee stated");
ok(/not a complete list/.test(html), "non-comprehensiveness stated");
ok(/some involve records or documents; others involve eligibility/i.test(html), "records-vs-eligibility distinction present");
ok(/bank\u200b|\bbank detail is missing/.test(html) || /bank detail is missing/.test(html), "bank/KYC rejection reason explained");
ok(/does not match Aadhaar/.test(html), "Aadhaar mismatch reason explained");
ok(/Employer approval demanded for a transfer claim/.test(html), "transfer-claim employer approval reason explained");
ok(/15 January 2025/.test(html), "transfer reform effective date stated");
ok(/April 2025/.test(html), "bank seeding reform date stated");
ok(/cancelled-cheque-leaf upload/.test(html), "cheque-leaf removal mentioned");
ok(/attested by one of the authorised officials/.test(html), "offline attestation requirement explained");
ok(/describe the offline route/.test(html), "Form 19 attestation scoped to offline route");
ok(/this page will not guess/.test(html), "unrecognised remarks handled honestly");
ok(/Eligibility rules: minimum balance and waiting period/.test(html), "eligibility reason present");
ok(/25% of contributions as a minimum balance/.test(html) && /minimum balance to 10%/.test(html), "25%-to-10% change stated");
ok(/12 months for final withdrawal/.test(html) && /to 2 months/.test(html), "12-to-2-month waiting change stated");
ok(/Lok Sabha written reply of 10 Aug 2026/.test(html) && /existing provisions/.test(html), "baseline 25%/12 months attributed to official statements");
ok(/not yet a rule in force/.test(html) && /notified after Ministry approval/.test(html) && /no effective date/.test(html), "pending-notification stated precisely");
ok(/PIB release, 19 Nov 2026/.test(html) && /PIB release of 19 Nov 2026/.test(html), "Nov 2026 source cited in body and sources");
ok(!/2\.57 days|7\.82%|23% to/.test(html), "no performance/timeline statistics presented as expectations");
ok(/PIB release, 16 Jun 2025/.test(html) || /PIB release of 16 Jun 2025/.test(html), "PIB source cited with date");
ok(/undated/.test(html), "undated FAQ caveat present");
ok(/No settlement-time promises/.test(html), "no-timeline-promise disclosure present");
ok(!/20 days|20-day|within 20/i.test(html), "no 20-day claim anywhere");
ok(!/camp day|10th of|27th of/i.test(html), "no camp-day claims");

// --- free-services warning ---
ok(!/98%|ninety-eight percent/i.test(html), "no unverifiable redressal stats");
ok(/EPFO's own services are free/.test(html), "free-services warning present, narrowed");
ok(!/no one is authorised to charge/.test(html), "no blanket unauthorised-agent claim");
ok(/guaranteed approval, priority processing/.test(html), "warning targets guaranteed-outcome payment");
ok(/EPFiGMS/.test(html) && /CPGRAMS/.test(html), "both grievance channels named");

// --- tracker behaviour (evaluated) ---
const scriptMatch = html.match(/<script>([\s\S]*)<\/script>/);
ok(!!scriptMatch, "script block present");
const src = scriptMatch[1].slice(0, scriptMatch[1].lastIndexOf("render();")) + "})();";
const store = {};
const localStorageStub = {
  getItem: k => (k in store ? store[k] : null),
  setItem: (k, v) => { store[k] = String(v); },
  removeItem: k => { delete store[k]; }
};
const listeners = {};
function el(id) {
  return {
    id, value: "", textContent: "", innerHTML: "", hidden: false,
    setAttribute(k, v) { this["attr_" + k] = v; },
    addEventListener(t, f) { listeners[id + ":" + t] = f; },
    closest() { return null; }
  };
}
const els = {};
const documentStub = { getElementById(id) { return els[id] || (els[id] = el(id)); } };
const windowObj = {};
new Function("window", "document", "localStorage", src)(windowObj, documentStub, localStorageStub);
const NS = windowObj.PFExplainer;
ok(NS && typeof NS.load === "function", "namespace exposed");

ok(NS.load().length === 0, "empty storage loads empty list");
store["pf-explainer-claims-v1"] = "not json";
ok(NS.load().length === 0, "corrupt JSON yields empty list, no throw");
store["pf-explainer-claims-v1"] = '{"a":1}';
ok(NS.load().length === 0, "non-array JSON yields empty list");

ok(NS.save([{ type: "t" }]) === true, "save succeeds");
ok(NS.load().length === 1 && NS.load()[0].type === "t", "round-trip preserves entry");

ok(NS.esc('<b>&"\'') === "&lt;b&gt;&amp;&quot;&#39;", "esc escapes all five specials");

// add-claim flow: missing type blocks and preserves input
const E = id => documentStub.getElementById(id);
E("fType").value = "";
E("fRemark").value = "some remark";
listeners["btnAdd:click"]();
ok(/Choose a claim type first/.test(E("addMsg").textContent), "missing type blocks save");
ok(E("fRemark").value === "some remark", "input preserved on blocked save");
ok(NS.load().length === 1, "nothing saved when blocked");

// valid add
E("fType").value = "Transfer claim";
E("fDate").value = "2026-11-20";
E("fRemark").value = "Name mismatch";
E("fStatus").value = "open";
E("fNote").value = "note";
listeners["btnAdd:click"]();
ok(NS.load().length === 2, "valid claim saved");
ok(NS.load()[1].type === "Transfer claim", "saved claim has type");
ok(E("fType").value === "" && E("fRemark").value === "", "form cleared after save");

// status cycle
const order = ["open", "resubmitted", "grievance", "settled"];
ok(JSON.stringify(Object.keys(NS.STATUSES)) === JSON.stringify(order), "status cycle order stable");

// render output escapes remark HTML
store["pf-explainer-claims-v1"] = JSON.stringify([{ type: "T", date: "", remark: "<img src=x>", status: "open", note: "" }]);
NS.render();
ok(E("claimList").innerHTML.indexOf("<img src=x>") === -1, "render escapes stored remark HTML");
ok(/&lt;img/.test(E("claimList").innerHTML), "escaped remark rendered as text");

// fictional sample labelled
ok(/Nothing is stored until you press Save claim/.test(html), "storage is opt-in and stated as such");
ok(/Fictional sample/.test(html), "sample data labelled fictional");

console.log(passed + " passed, " + failed + " failed");
process.exit(failed ? 1 : 0);
